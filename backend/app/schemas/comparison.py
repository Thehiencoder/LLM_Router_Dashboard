from pydantic import BaseModel, Field
from typing import List, Optional, Literal


class ModelSelection(BaseModel):
    """Specification of a specific provider model to query."""
    provider: Literal["openai", "anthropic", "gemini"] = Field(
        ...,
        description="Target vendor: 'openai', 'anthropic', or 'gemini'",
    )
    model: str = Field(
        ...,
        min_length=1,
        description="Target model identifier, e.g. 'gpt-4.5-preview', 'claude-3-7-sonnet', 'gemini-3.0-flash'",
    )


class CompareRequest(BaseModel):
    """Payload for comparing prompt responses across multiple models."""
    prompt: str = Field(
        ...,
        min_length=1,
        description="User prompt text to evaluate across all selected models",
    )
    system_prompt: Optional[str] = Field(
        default=None,
        description="Optional system instruction / role context",
    )
    models: List[ModelSelection] = Field(
        ...,
        min_length=1,
        max_length=6,
        description="List of selected models to benchmark concurrently",
    )
    temperature: Optional[float] = Field(
        default=0.7,
        ge=0.0,
        le=2.0,
        description="Sampling temperature (sanitized for reasoning models that disallow custom temp)",
    )
    max_tokens: Optional[int] = Field(
        default=2048,
        ge=1,
        le=16384,
        description="Maximum response completion tokens to generate",
    )


class TokenMetrics(BaseModel):
    """Detailed token count breakdown extracted from provider usage metadata."""
    input_tokens: int = Field(default=0, ge=0)
    output_tokens: int = Field(default=0, ge=0)
    total_tokens: int = Field(default=0, ge=0)
    reasoning_tokens: Optional[int] = Field(
        default=0,
        ge=0,
        description="Internal thinking/reasoning tokens generated by models like o1, o3-mini, claude-3-7-sonnet",
    )
    cached_tokens: Optional[int] = Field(default=0, ge=0)


class CostMetrics(BaseModel):
    """Calculated financial metrics differentiating free-tier from commercial rates."""
    is_free_tier: bool = Field(
        default=False,
        description="True if request runs under a $0.00 free tier (e.g., Google AI Studio)",
    )
    actual_cost_usd: float = Field(
        default=0.0,
        description="Actual out-of-pocket invoice cost ($0.00 for free tier keys)",
    )
    estimated_list_cost_usd: float = Field(
        default=0.0,
        description="Equivalent nominal commercial list price for cross-model economic benchmarking",
    )
    input_cost_usd: float = Field(default=0.0)
    output_cost_usd: float = 0.0
    total_cost_usd: float = Field(
        default=0.0,
        description="Total cost metric for backward-compatibility (matches actual_cost_usd if paid, or list price if free)",
    )


class LLMResult(BaseModel):
    """Normalized response schema returned for every benchmarked model."""
    provider: str = Field(..., description="Provider name: 'openai', 'anthropic', 'gemini'")
    model: str = Field(..., description="Exact model identifier queried")
    text: Optional[str] = Field(default=None, description="Generated response content or markdown")
    tokens: TokenMetrics = Field(default_factory=TokenMetrics)
    cost: CostMetrics = Field(default_factory=CostMetrics)
    latency_ms: float = Field(default=0.0, description="Inference turnaround latency in milliseconds")
    error: Optional[str] = Field(default=None, description="Error message if inference failed for this model")
    status: Literal["success", "error"] = Field(
        default="success",
        description="Completion status: 'success' | 'error'",
    )


class CompareResponse(BaseModel):
    """Response returned to the React frontend containing all model results."""
    prompt: str
    total_latency_ms: float = Field(..., description="Total wall-clock time for concurrent batch completion")
    results: List[LLMResult] = Field(default_factory=list)


class ModelPricingRates(BaseModel):
    input_price_per_million: float
    output_price_per_million: float
    is_free_tier_eligible: bool = False


class ModelInfo(BaseModel):
    id: str
    name: str
    provider: Literal["openai", "anthropic", "gemini"]
    category: str
    description: str
    pricing: ModelPricingRates
    is_default: bool = False


class ModelsCatalogResponse(BaseModel):
    models: List[ModelInfo]
